#include <iostream>
using namespace std;

/**
 * ?????????????????????????????????
 * @param arr ??????????????????
 * @param n ????????
 */
void selectionSort(int arr[], int n)
{
    // ???????????????????¦Ë??
    for (int i = 0; i < n - 1; i++)
    {
        int min_idx = i;
        // ?????????¦Ä????????§³???????
        for (int j = i + 1; j < n; j++)
        {
            if (arr[j] < arr[min_idx])
            {
                min_idx = j;
            }
        }
        // ?????????§³???????????¦Ë??
        swap(arr[i], arr[min_idx]);
    }
}

